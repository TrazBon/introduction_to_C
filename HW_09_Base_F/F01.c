// Всю программу загружать не надо, только одну эту функцию. Можно просто закомментировать текст всей программы, кроме данной функции.

void sort_array(int size, int a[])
{
  short isMooved;
  do{
    isMooved = 0;
    for (short i = 0; i < size - 1; i++)
    {
      if(a[i] > a[i+1])
      {
        int tmp = a[i];
        a[i] = a[i+1];
        a[i+1] = tmp;
        isMooved = 1;
      }
    }  
  } while (isMooved);
}